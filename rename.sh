#!/bin/bash
# Переименовывает все файлы в ./cto в порядковые имена (1.png, 2.png, ...)
# Сохраняет расширение каждого файла. Порядок — по имени (с естественной сортировкой по числу).

set -e
cd "$(dirname "$0")/corrections" || exit 1

# Временный префикс, чтобы не перезаписать существующие файлы при переименовании
PREFIX="__ren_"
list=$(mktemp)
trap 'rm -f "$list"' EXIT

# Собираем список файлов с числовым ключом для сортировки (извлекаем число из имени или используем 0)
for f in *; do
  [ -f "$f" ] || continue
  # Если в имени есть число в скобках типа "1 (N)" — используем N, иначе — 0
  num=$(echo "$f" | sed -n 's/.*(\([0-9]*\)).*/\1/p')
  [ -z "$num" ] && num=0
  printf "%d\t%s\n" "$num" "$f"
done | sort -n -k1 > "$list"

# Фаза 1: переименовываем во временные имена
n=1
while IFS=$'\t' read -r _ name; do
  ext="${name##*.}"
  [ "$name" = "$ext" ] && ext=""
  [ -n "$ext" ] && ext=".$ext"
  mv -- "$name" "${PREFIX}${n}${ext}"
  n=$((n + 1))
done < "$list"

# Фаза 2: убираем префикс
for f in "${PREFIX}"*; do
  [ -e "$f" ] || continue
  new="${f#${PREFIX}}"
  mv -- "$f" "$new"
  echo "$f -> $new"
done

echo "Готово: переименовано файлов: $((n - 1))"
